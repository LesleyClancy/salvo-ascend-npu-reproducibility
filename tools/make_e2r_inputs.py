"""E2R frozen inputs: 9 chat-templated prompts x 2 models.

Per prompt:
  L = the model's chat token length (prefix is the complete chat prompt),
  N = min(64, tokens generated by the deployed fp16 T=1 graph until EOS).

The runtime exactness reference is the fp16 ONNX greedy sequence (`gen_ids`),
not HF fp32: the fp16 graph diverges from HF at a few positions (recorded as
hf_diff).  The prefix cache and prefix_logits come from the same fp16 graph.
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

import numpy as np
import torch

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from src.adapters.qwen25 import (  # noqa: E402
    DEFAULT_MANIFEST as QWEN25_MANIFEST,
    load_geometry as qwen25_geometry,
    load_manifest as qwen25_manifest,
)
from src.adapters.qwen3 import (  # noqa: E402
    DEFAULT_MANIFEST as QWEN3_MANIFEST,
    load_geometry as qwen3_geometry,
    load_manifest as qwen3_manifest,
)

CAPACITY = 256
MAX_NEW = 64
MIN_N = 16


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def encode(tok, text: str, is_qwen3: bool) -> list[int]:
    kwargs = {"enable_thinking": False} if is_qwen3 else {}
    s = tok.apply_chat_template(
        [{"role": "user", "content": text}],
        tokenize=False, add_generation_prompt=True, **kwargs)
    return tok(s, return_tensors="pt").input_ids[0].tolist()


def hf_greedy(model_dir: Path, ids: list[int], max_new: int, eos: int) -> list[int]:
    from transformers import AutoModelForCausalLM
    from transformers.cache_utils import DynamicCache

    hf = AutoModelForCausalLM.from_pretrained(str(model_dir), dtype=torch.float32)
    hf.eval()
    gen: list[int] = []
    cache = DynamicCache()
    with torch.no_grad():
        out = hf(torch.tensor([ids]), past_key_values=cache, use_cache=True)
        cur = len(ids)
        while len(gen) < max_new:
            nxt = int(out.logits[0, -1].argmax())
            gen.append(nxt)
            if nxt == eos:
                break
            out = hf(torch.tensor([[nxt]]), past_key_values=cache, use_cache=True,
                     cache_position=torch.tensor([cur]))
            cur += 1
    del hf
    return gen


def build_case(model_key: str, geom, onnx_path: Path, prompt: dict,
               out_dir: Path, log, hf_fn=hf_greedy) -> dict:
    import onnxruntime as ort
    from transformers import AutoTokenizer

    man = (qwen25_manifest(QWEN25_MANIFEST) if model_key == "qwen25_05b"
           else qwen3_manifest(QWEN3_MANIFEST))
    cfg = json.loads((Path(man["local_dir"]) / "config.json").read_text(encoding="utf-8"))
    eos = cfg["eos_token_id"]
    eos = eos[0] if isinstance(eos, list) else eos
    tok = AutoTokenizer.from_pretrained(man["local_dir"])
    ids = encode(tok, prompt["text"], model_key == "qwen3_06b")
    L = len(ids)
    # The runtime reference is the deployed fp16 graph, so the fp32 HF pass is
    # diagnostic only.  Callers building large subsets pass hf_fn=None rather
    # than reloading a 1 GB fp32 model per prompt.
    hf_gen = None if hf_fn is None else hf_fn(Path(man["local_dir"]), ids, MAX_NEW, eos)

    spec = geom.spec
    layers, kvh, hd = spec.num_layers, spec.num_kv_heads, spec.head_dim
    sess = ort.InferenceSession(str(onnx_path), providers=["CPUExecutionProvider"])
    k = np.zeros((layers, kvh, CAPACITY, hd), dtype=np.float16)
    v = np.zeros_like(k)

    def run(token: int, pos: int):
        feeds = {
            "input_ids": np.array([[token]], dtype=np.int64),
            "position_ids": np.array([[pos]], dtype=np.int64),
            "k_cache": k, "v_cache": v,
        }
        logits, dk, dv = sess.run(None, feeds)
        return (logits[0, 0].astype(np.float32),
                dk[:, :, 0, :].astype(np.float16),
                dv[:, :, 0, :].astype(np.float16))

    prefix_logits = None
    for p in range(L):
        lg, dk, dv = run(ids[p], p)
        if p == L - 1:
            prefix_logits = lg
        k[:, :, p, :] = dk
        v[:, :, p, :] = dv
    kp, vp = k.copy(), v.copy()

    gen = [int(np.argmax(prefix_logits))]
    row_argmax: list[int] = []
    if gen[0] != eos:
        for i in range(MAX_NEW - 1):
            lg, dk, dv = run(gen[i], L + i)
            nxt = int(np.argmax(lg))
            row_argmax.append(nxt)
            gen.append(nxt)
            k[:, :, L + i, :] = dk
            v[:, :, L + i, :] = dv
            if nxt == eos:
                break
    N = len(gen)
    # row_argmax[i] is the argmax at position L+i (predicts gen[i+1]).
    # The last row predicts beyond the generated sequence; it is not used.
    if len(row_argmax) < N:
        row_argmax.append(0)
    ref_argmax = np.array(row_argmax[:N], dtype=np.int64)

    hf_diff = None if hf_gen is None else sum(1 for a, b in zip(gen, hf_gen) if a != b)
    log(f"=== {model_key} / {prompt['id']} ({prompt['category']}) ===")
    log(f"L={L} N={N} usable={N >= MIN_N} eos={gen[-1] == eos} "
        f"hf_diff={hf_diff} hf_N={None if hf_gen is None else len(hf_gen)}")
    log(f"fp16_gen={gen}")
    log(f"hf_gen  ={hf_gen}")

    out_dir.mkdir(parents=True, exist_ok=True)
    files = {}

    def save(name: str, arr: np.ndarray, dtype) -> None:
        path = out_dir / name
        np.ascontiguousarray(arr.astype(dtype)).tofile(path)
        files[name] = {"bytes": path.stat().st_size, "dtype": np.dtype(dtype).name,
                       "shape": list(arr.shape), "sha256": sha256_file(path)}

    save("prefix_ids.bin", np.array(ids), np.int64)
    save("k_prefix.bin", kp, np.float16)
    save("v_prefix.bin", vp, np.float16)
    save("prefix_logits.bin", prefix_logits, np.float32)
    save("timed_ids.bin", np.array(gen), np.int64)
    save("ref_argmax.bin", ref_argmax, np.int64)
    save("gen_ids.bin", np.array(gen), np.int64)
    (out_dir / "geom.txt").write_text(
        f"{layers} {kvh} {CAPACITY} {hd}\n", encoding="utf-8")
    files["geom.txt"] = {"bytes": (out_dir / "geom.txt").stat().st_size,
                         "text": (out_dir / "geom.txt").read_text().strip(),
                         "sha256": sha256_file(out_dir / "geom.txt")}
    meta = {
        "task": "E2R", "model": model_key, "model_id": man["model_id"],
        "prompt_id": prompt["id"], "category": prompt["category"],
        "prompt": prompt["text"], "L": L, "N": N, "usable": N >= MIN_N,
        "capacity": CAPACITY, "eos_token_id": int(eos),
        "prefix_ids": ids, "gen_ids": gen, "hf_gen": hf_gen,
        "hf_diff": hf_diff, "hf_N": None if hf_gen is None else len(hf_gen),
        "reference": "deployed fp16 T=1 ONNX greedy sequence",
        "files": files,
    }
    (out_dir / "meta.json").write_text(json.dumps(meta, indent=2) + "\n",
                                        encoding="utf-8")
    files["meta.json"] = {"bytes": (out_dir / "meta.json").stat().st_size,
                          "sha256": sha256_file(out_dir / "meta.json")}
    return {"model": model_key, "prompt_id": prompt["id"],
            "category": prompt["category"], "L": L, "N": N,
            "usable": N >= MIN_N, "eos": bool(gen[-1] == eos),
            "hf_diff": hf_diff, "hf_N": None if hf_gen is None else len(hf_gen),
            "gen_ids": gen, "hf_gen": hf_gen, "files": files}


def main() -> int:
    lines = []

    def log(msg: str = "") -> None:
        print(msg)
        lines.append(msg)

    prompts = json.loads((REPO_ROOT / "cases/dev/e1_prompts.json").read_text())["prompts"]
    log("=" * 78)
    log("E2R frozen inputs: 9 chat prompts x 2 models; L=chat length, N<=64")
    log("Reference: deployed fp16 T=1 ONNX greedy; HF fp32 divergence recorded")
    log("=" * 78)
    models = {
        "qwen25_05b": (QWEN25_MANIFEST, qwen25_manifest, qwen25_geometry),
        "qwen3_06b": (QWEN3_MANIFEST, qwen3_manifest, qwen3_geometry),
    }
    case = {"task": "E2R", "capacity": CAPACITY, "max_new": MAX_NEW,
            "min_n": MIN_N, "prompts": prompts, "models": {}}
    all_ok = True
    for key, (mfile, mload, gload) in models.items():
        man = mload(mfile)
        geom = gload(man["local_dir"], man)
        onnx_path = REPO_ROOT / "artifacts" / "e2r" / key / "g1.onnx"
        case["models"][key] = {"model_id": man["model_id"],
                               "onnx": str(onnx_path.relative_to(REPO_ROOT)).replace("\\", "/"),
                               "onnx_sha256": sha256_file(onnx_path),
                               "cases": {}}
        for p in prompts:
            out_dir = REPO_ROOT / "cases" / "dev" / f"e2r_inputs_{key}_{p['id']}"
            info = build_case(key, geom, onnx_path, p, out_dir, log)
            case["models"][key]["cases"][p["id"]] = info
            all_ok = all_ok and info["N"] >= 1
            log("")

    case_path = REPO_ROOT / "cases/dev/e2r_case.json"
    case_path.write_text(json.dumps(case, indent=2) + "\n", encoding="utf-8")
    log(f"case: {case_path.relative_to(REPO_ROOT)} sha256={sha256_file(case_path)}")
    log(f"VERDICT: {'PASS' if all_ok else 'FAIL'} (inputs generated; "
        "fp16 reference; HF diff recorded)")
    raw = REPO_ROOT / "raw" / "E2R_inputs_2026-10-23.txt"
    raw.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"log written: {raw}")
    return 0 if all_ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
